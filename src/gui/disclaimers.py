import streamlit as st

# מודול ייעודי לגילויי-נאות (disclaimers) - הופרד מ-ui_helpers.py כדי לא לחצות את מגבלת
# 150 השורות לקובץ. התוכן (קבועים ברמת המודול) מופרד מהחיווט (פונקציות render) כדי שהעובדות
# יהיו ניתנות לבדיקה יחידתית ללא Streamlit.

# --- גילוי נאות 1: מגבלות שכבת ה-API החינמית ---
# העובדות חייבות להישאר עקביות עם ApiGatekeeper (services/gatekeeper.py): Mouser מוגבל
# ל-30 שאילתות לדקה ו-1,000 ליום. הניסוח נמנע ממקפים/לוכסנים בין מספרים (למשל "30/1,000"),
# שכן רצף תווים נייטרליים כזה מתהפך ויזואלית בהקשר RTL; במקום זאת המספרים משובצים במילים.
_API_LIMITS_DISCLAIMER = (
    "**מגבלות שירות · שכבת API חינמית**\n\n"
    "המערכת מסתמכת על שירותי API בשכבת שימוש חינמית (free-tier) הכפופים למכסות נוקשות. "
    "ממשק **Mouser** מוגבל ל-1,000 שאילתות ליום ול-30 שאילתות לדקה. יתר הספקים "
    "(**DigiKey** וכן **Nexar (Octopart)**) כפופים אף הם למכסות חינמיות מחמירות משלהם.\n\n"
    "לפיכך, ניתוח עצי מוצר (BOM) גדולים במיוחד או ריצות ניתוח חוזרות ורבות עלולים למצות את "
    "המכסה היומית. כדי לשמר שאילתות, המערכת שומרת במטמון את תוצאות הניתוח עבור כל קובץ, כך "
    "שניתוח חוזר של אותו קובץ אינו צורך מכסה נוספת."
)

# --- גילוי נאות 2: שימוש שאינו מסחרי ---
_NONCOMMERCIAL_DISCLAIMER = (
    "**תנאי שימוש**\n\n"
    "התוכנה מיועדת לשימוש אישי ופנימי בלבד, למטרות שאינן מסחריות. אין לעשות בה כל שימוש "
    "מסחרי."
)

# כותרת ה-expander המכווץ (ממוקם מתחת ל-expander ההסבר הראשי; מכווץ כברירת מחדל כדי לא
# להעמיס על זרימת הניתוח, אך גלוי וזמין לחיפוש בכל עת).
_DISCLAIMER_EXPANDER_TITLE = "⚠️ מגבלות שירות ותנאי שימוש"

# כיתוב תחתית תמציתי (שורה אחת) המוצג בסוף העמוד - תזכורת קבועה ומינימלית. הנקודה המפרידה
# (·) היא תו נייטרלי בטוח בהקשר RTL כאשר אין רצפי ספרות סמוכים לו.
_FOOTER_CAPTION = (
    "לשימוש אישי, פנימי ובלתי-מסחרי בלבד · השירות מסתמך על מכסות API חינמיות מוגבלות"
)


def render_disclaimers() -> None:
    """מציג את שני גילויי הנאות (מגבלות ה-API ותנאי השימוש) בתוך st.expander מכווץ.

    ממוקם מיד מתחת ל-expander ההסבר הראשי. מכווץ כברירת מחדל (expanded=False) כדי לשמור על
    זרימת ניתוח נקייה, אך נשאר גלוי וניתן לגילוי - יישום "Aesthetic and Minimalist Design"
    לצד שקיפות מלאה על מגבלות השירות."""
    with st.expander(_DISCLAIMER_EXPANDER_TITLE, expanded=False):
        st.markdown(_API_LIMITS_DISCLAIMER)
        st.divider()
        st.markdown(_NONCOMMERCIAL_DISCLAIMER)


def render_footer() -> None:
    """מציג כיתוב תחתית תמציתי (שורה אחת) בתחתית העמוד - תזכורת קבועה ובלתי-פולשנית."""
    st.divider()
    st.caption(_FOOTER_CAPTION)
